"""
The hifps addon's machine-code stubs for HiFi XI's C++ port (src/game/hifps): its proxy/build.py assembles
proxy/<name>.asm and writes proxy/<name>.blob (for its harnesses) and <name>_code.lua (for hifps.lua); this reads
both, checks they agree, and writes src/game/hifps/stubs.inc: each stub's bytes, size, symbol offsets and relocations
(the offsets of the DIR32 words that get the base of the copy added, as hifps.lua lays them down). The .asm stays the
single source: run the addon's proxy/build.py after changing it, then this.

    python tools/hifps_stubs.py [<hifps addon folder>] [<out .inc>]

Reads only: the addon's files are left as they are.
"""

import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ADDON = r'C:\Games\PhoenixXI\addons\hifps'
OUT = os.path.join(ROOT, 'src', 'game', 'hifps', 'stubs.inc')
STUBS = ('proxy', 'walls')  # (gfx.asm, the addon's lamps and night lighting, isn't HiFi XI's)


def parse_lua(path):
    """size, [(name, offset)] in the module's order, relocations, bytes from <name>_code.lua"""
    text = open(path, encoding='utf-8').read()
    size = int(re.search(r'\bsize\s*=\s*(\d+)', text).group(1))
    sym_text = re.search(r'\bsym\s*=\s*\{([^}]*)\}', text).group(1)
    syms = [(n, int(v, 16)) for n, v in re.findall(r'(\w+)\s*=\s*0x([0-9A-Fa-f]+)', sym_text)]
    reloc_text = re.search(r'\brelocs\s*=\s*\{([^}]*)\}', text).group(1)
    relocs = [int(v, 16) for v in re.findall(r'0x([0-9A-Fa-f]+)', reloc_text)]
    hex_text = re.search(r'\bhex\s*=\s*table\.concat\(\{(.*?)\}\)', text, re.S).group(1)
    code = bytes.fromhex(''.join(re.findall(r"'([0-9A-Fa-f]*)'", hex_text)))
    return size, syms, relocs, code


def parse_blob(path):
    """size, symbol offsets (in the module's order), relocations, bytes from <name>.blob"""
    d = open(path, 'rb').read()
    size, nrel, nsym = struct.unpack_from('<III', d, 0)
    relocs = list(struct.unpack_from('<%dI' % nrel, d, 12))
    syms = list(struct.unpack_from('<%dI' % nsym, d, 12 + 4 * nrel))
    code = d[12 + 4 * (nrel + nsym):]
    return size, syms, relocs, code


def stub(addon, name):
    lua = parse_lua(os.path.join(addon, name + '_code.lua'))
    blob = parse_blob(os.path.join(addon, 'proxy', name + '.blob'))
    size, syms, relocs, code = lua
    problems = []
    if blob[0] != size or len(code) != size or len(blob[3]) != size:
        problems.append('sizes differ (lua %d, its bytes %d, blob %d, its bytes %d)' % (size, len(code), blob[0], len(blob[3])))
    if blob[3] != code:
        problems.append('the bytes differ')
    if blob[2] != relocs:
        problems.append('the relocations differ')
    if blob[1] != [v for _, v in syms]:
        problems.append('the symbols differ')
    if relocs != sorted(set(relocs)) or any(r + 4 > size for r in relocs):
        problems.append('a relocation is out of order or outside the stub')
    if problems:
        sys.exit('%s: %s_code.lua and proxy/%s.blob disagree: %s (run its proxy/build.py again)' % (name, name, name, '; '.join(problems)))
    return size, syms, relocs, code


def emit(name, size, syms, relocs, code):
    out = ['\t// %s: proxy/%s.asm (%d bytes, %d relocations, %d symbols)' % (name, name, size, len(relocs), len(syms)),
           '\tnamespace %s' % name, '\t{', '\t\tconstexpr uint32_t size = %d;' % size]
    for n, v in syms:
        out.append('\t\tconstexpr uint32_t %s = 0x%X;' % (n, v))
    out.append('\t\t// (in the .asm\'s order, as the blob and the harness list them)')
    out.append('\t\tconstexpr uint32_t symbols[%d] = { %s };' % (len(syms), ', '.join(n for n, _ in syms)))
    out.append('\t\tconstexpr uint32_t relocs[%d] = {' % len(relocs))
    for i in range(0, len(relocs), 12):
        out.append('\t\t\t' + ', '.join('0x%X' % r for r in relocs[i:i + 12]) + ',')
    out.append('\t\t};')
    out.append('\t\tconstexpr uint8_t bytes[%d] = {' % size)
    for i in range(0, len(code), 24):
        out.append('\t\t\t' + ', '.join('0x%02X' % b for b in code[i:i + 24]) + ',')
    out.append('\t\t};')
    out.append('\t}')
    return out


def main():
    addon = sys.argv[1] if len(sys.argv) > 1 else ADDON
    path = sys.argv[2] if len(sys.argv) > 2 else OUT
    lines = ['// Generated by tools/hifps_stubs.py from the hifps addon\'s proxy/*.blob and *_code.lua (its proxy/build.py',
             '// assembles proxy/*.asm into both); do not edit. Each stub: its size, symbol offsets, relocations (offsets of the',
             '// words that get the base of the copy added) and bytes, as hifps.lua lays them down.',
             '',
             'namespace stubs',
             '{']
    for i, name in enumerate(STUBS):
        size, syms, relocs, code = stub(addon, name)
        if i > 0:
            lines.append('')
        lines += emit(name, size, syms, relocs, code)
        print('%s: %d bytes, %d relocations, %d symbols' % (name, size, len(relocs), len(syms)))
    lines.append('}')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
