"""Copies hifps's sigs.lua (tools/gen_sigs.py's signatures for every client offset its site tables name) into
src/game/hifps/sites.cpp, between its '// sigs.lua: begin' and '// sigs.lua: end' lines. Run it again after
gen_sigs.py has rebuilt sigs.lua.

Usage: python tests/hifps_sigs_cpp.py [<sigs.lua>]   (default: C:/Games/PhoenixXI/addons/hifps/sigs.lua)
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITES = os.path.join(HERE, '..', 'src', 'game', 'hifps', 'sites.cpp')
SIGS = sys.argv[1] if len(sys.argv) > 1 else 'C:/Games/PhoenixXI/addons/hifps/sigs.lua'

src = open(SIGS, encoding='utf-8').read()
head = re.search(r'^-- Generated by tools/gen_sigs.py from (\S+);', src, re.M)
rows = re.findall(r"\[0x([0-9A-Fa-f]+)\] = \{ '(\w+)', (\d+), '([0-9A-F?]+)' \}", src)
if not rows:
    sys.exit('no signatures in %s' % SIGS)
lines = ['\t\t\t// (tests/hifps_sigs_cpp.py, from %s: %s; %d signatures)' % (os.path.basename(SIGS), head.group(1) if head else '?', len(rows))]
for rva, kind, off, pat in sorted(rows, key=lambda r: int(r[0], 16)):
    lines.append('\t\t\t{ 0x%06X, kind::%s, %s, "%s" },' % (int(rva, 16), kind, off, pat))

text = open(SITES, encoding='utf-8').read()
begin, end = text.index('// sigs.lua: begin\n') + len('// sigs.lua: begin\n'), text.index('\t\t\t// sigs.lua: end')
text = text[:begin] + '\n'.join(lines) + '\n' + text[end:]
with open(SITES, 'w', encoding='utf-8', newline='\n') as f:
    f.write(text)
print('wrote %d signatures into %s' % (len(rows), os.path.normpath(SITES)))
